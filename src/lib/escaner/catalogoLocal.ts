/**
 * Busca un producto en el catálogo local offline verificando todas las variantes de código de barras.
 */
export function buscarEnCatalogoLocal(codigoBarras: string): ProductoEscaneado | null {
  const limpio = codigoBarras.trim().replace(/\D/g, '');
  if (!limpio) return null;

  // Variantes posibles: directo, con cero inicial si tiene 12 dígitos, o sin cero si tiene 13 y empieza con 0
  const posibles = [limpio];
  if (limpio.length === 12) posibles.push(`0${limpio}`);
  if (limpio.length === 13 && limpio.startsWith('0')) posibles.push(limpio.slice(1));

  const item = CATALOGO_PRODUCTOS_LOCALES.find((it) =>
    it.codigos.some((c) => posibles.includes(c.replace(/\D/g, ''))),
  );

  if (!item) return null;

  const aditivosAnalizados = (item.aditivosCodigos || []).map((c) => clasificarAditivo(c));

  const puntaje = calcularPuntajeSalud({
    nutrientes: item.nutrientes,
    novaGroup: item.novaGroup,
    aditivosAnalizados,
    categoriaTags: item.categoriaTags,
    esLiquido: Boolean(item.esLiquido),
    ingredientesTexto: item.ingredientesTexto,
  });

  return {
    codigoBarras: limpio,
    nombre: item.nombre,
    marca: item.marca,
    categoria: item.categoria,
    categoriaTags: item.categoriaTags,
    imagenUrl: item.imagenUrl,
    nutriScoreGrade: item.nutriScoreGrade,
    novaGroup: item.novaGroup,
    ecoScoreGrade: item.ecoScoreGrade,
    ingredientesTexto: item.ingredientesTexto,
    alergenos: item.alergenos || [],
    trazasAlergenos: item.trazasAlergenos || [],
    aditivos: aditivosAnalizados,
    nutrientes: item.nutrientes,
    esLiquido: Boolean(item.esLiquido),
    puntaje,
    fuente: 'catalogo_local',
    fechaEscaneo: Date.now(),
  };
}
